// Helper to generate 60 days of realistic attendance
export function generateMockAttendanceList(): any[] {
  const list: any[] = [];
  let idCounter = 1;
  const today = new Date();

  for (let d = 59; d >= 0; d--) {
    const currDate = new Date(today.getTime() - d * 86400000);
    const dateStr = currDate.toISOString().slice(0, 10);
    const dayOfWeek = currDate.getDay();

    for (const staff of MOCK_STAFF_LIST) {
      const isWeekOff = (staff.id % 7 === dayOfWeek);
      if (isWeekOff) {
        list.push({
          id: idCounter++,
          staff_id: staff.id,
          staff_code: staff.staff_code,
          staff_name: `${staff.first_name} ${staff.last_name}`,
          department_name: staff.department_name,
          date: dateStr,
          shift_id: 1,
          shift_name: 'Morning Retail Shift',
          check_in: null,
          check_out: null,
          status: 'WEEK_OFF',
          work_duration_minutes: 0,
          late_minutes: 0,
          overtime_minutes: 0,
          notes: 'Scheduled Weekly Off',
        });
        continue;
      }

      const rand = ((staff.id * 17 + d * 23) % 100);
      let status = 'PRESENT';
      let checkIn = '08:52:00';
      let checkOut = '18:05:00';
      let lateMinutes = 0;
      let duration = 510;
      let overtime = (staff.id % 3 === 0 && (d % 6 === 0)) ? 60 : 0;

      if (rand < 5) {
        status = 'LATE';
        checkIn = '09:25:00';
        lateMinutes = 25;
        duration = 485;
      } else if (rand === 5) {
        status = 'HALF_DAY';
        checkIn = '09:00:00';
        checkOut = '13:30:00';
        duration = 270;
      } else if (rand === 6) {
        status = 'ON_LEAVE';
        checkIn = null as any;
        checkOut = null as any;
        duration = 0;
      }

      list.push({
        id: idCounter++,
        staff_id: staff.id,
        staff_code: staff.staff_code,
        staff_name: `${staff.first_name} ${staff.last_name}`,
        department_name: staff.department_name,
        date: dateStr,
        shift_id: (staff.id % 2 === 0 ? 2 : 1),
        shift_name: staff.id % 2 === 0 ? 'Evening Retail Shift' : 'Morning Retail Shift',
        check_in: checkIn ? `${dateStr} ${checkIn}` : null,
        check_out: checkOut ? `${dateStr} ${checkOut}` : null,
        status,
        work_duration_minutes: duration,
        late_minutes: lateMinutes,
        overtime_minutes: overtime,
        biometric_verified: checkIn ? 1 : 0,
      });
    }
  }

  return list;
}

